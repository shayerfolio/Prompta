import { access, chmod, mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';

export const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const stateDirectory = resolve(root, '.prompta');
export const statePath = resolve(stateDirectory, 'setup.json');
export const secretsPath = resolve(stateDirectory, 'secrets.json');
export const configPath = resolve(root, 'wrangler.config.json');
export const localDataPath = resolve(stateDirectory, 'local-state');

export async function exists(path) {
  try { await access(path); return true; } catch { return false; }
}

export function requireNode() {
  const [major, minor] = process.versions.node.split('.').map(Number);
  if (major < 22 || (major === 22 && minor < 12)) {
    throw new Error('Prompta needs Node.js 22.12 or newer. Install a current LTS release from https://nodejs.org/.');
  }
}

export async function readJson(path, optional = false) {
  try { return JSON.parse(await readFile(path, 'utf8')); }
  catch (error) {
    if (optional && error.code === 'ENOENT') return undefined;
    throw new Error(`Cannot read ${path.endsWith('secrets.json') ? 'the local server secrets' : path}. Restore the file or run npm run setup.`, { cause: error });
  }
}

export async function writePrivate(path, value) {
  await mkdir(dirname(path), { recursive: true, mode: 0o700 });
  const temporary = `${path}.${process.pid}.tmp`;
  await writeFile(temporary, value, { mode: 0o600 });
  await chmod(temporary, 0o600);
  await rename(temporary, path);
  await chmod(path, 0o600);
}

export function validateSetup(state, secrets) {
  if (state?.format !== 1 || !/^[a-z][a-z0-9-]{2,47}$/.test(state.workerName ?? '') ||
      !/^[a-z][a-z0-9-]{2,62}$/.test(state.databaseName ?? '') ||
      !/^shared:[0-9a-f-]{36}$/i.test(state.workspaceId ?? '') ||
      typeof state.backups !== 'boolean' ||
      (state.backups && !/^[a-z][a-z0-9-]{2,62}$/.test(state.backupBucketName ?? '')) ||
      (state.databaseId && !/^[0-9a-f-]{36}$/i.test(state.databaseId)) ||
      (state.accountId && !/^[0-9a-f]{32}$/i.test(state.accountId))) {
    throw new Error('The saved deployment configuration is invalid. Review .prompta/setup.json or run npm run setup.');
  }
  if (!/^pbkdf2-sha256:100000:[A-Za-z0-9_-]{22}:[A-Za-z0-9_-]{43}$/.test(secrets?.PROMPTA_PIN_HASH ?? '') ||
      !/^[A-Za-z0-9_-]{43}$/.test(secrets?.PROMPTA_SESSION_SECRET ?? '')) {
    throw new Error('The local server secrets are missing or invalid. Run npm run setup.');
  }
}

export async function loadSetup() {
  const state = await readJson(statePath, true);
  const secrets = await readJson(secretsPath, true);
  if (!state || !secrets) throw new Error('Prompta has not been set up. Run npm run setup first.');
  validateSetup(state, secrets);
  return { state, secrets };
}

export async function writeConfiguration(state, secrets) {
  validateSetup(state, secrets);
  const template = await readJson(resolve(root, 'wrangler.jsonc'));
  const config = {
    ...template,
    name: state.workerName,
    vars: { ...template.vars, PROMPTA_WORKSPACE_ID: state.workspaceId },
    d1_databases: [{
      binding: 'DB',
      database_name: state.databaseName,
      database_id: state.databaseId || '00000000-0000-0000-0000-000000000000',
      migrations_dir: 'migrations',
    }],
    triggers: { crons: ['0 21 * * *'] },
  };
  delete config.vars.PROMPTA_ALLOW_INSECURE_LOCAL_DEV;
  delete config.vars.PROMPTA_PIN_HASH;
  delete config.vars.PROMPTA_SESSION_SECRET;
  delete config.account_id;
  if (state.accountId) config.account_id = state.accountId;
  if (state.backups) config.r2_buckets = [{ binding: 'BACKUPS', bucket_name: state.backupBucketName }];
  else delete config.r2_buckets;
  await writePrivate(configPath, `${JSON.stringify(config, null, 2)}\n`);
  const vars = {
    PROMPTA_PIN_HASH: secrets.PROMPTA_PIN_HASH,
    PROMPTA_SESSION_SECRET: secrets.PROMPTA_SESSION_SECRET,
    PROMPTA_WORKSPACE_ID: state.workspaceId,
    PROMPTA_ALLOW_INSECURE_LOCAL_DEV: 'true',
  };
  await writePrivate(resolve(root, '.dev.vars'),
    '# Local Worker secrets. Generated by npm run setup. Do not commit or distribute.\n' +
    Object.entries(vars).map(([key, value]) => `${key}=${JSON.stringify(value)}`).join('\n') + '\n');
}

export async function saveSetup(state, secrets) {
  validateSetup(state, secrets);
  await mkdir(stateDirectory, { recursive: true, mode: 0o700 });
  await chmod(stateDirectory, 0o700);
  await writePrivate(secretsPath, `${JSON.stringify(secrets, null, 2)}\n`);
  await writePrivate(statePath, `${JSON.stringify(state, null, 2)}\n`);
  await writeConfiguration(state, secrets);
}

export function command(program, args, options = {}) {
  return new Promise((resolvePromise, reject) => {
    const capture = Boolean(options.capture || options.sensitive);
    const child = spawn(program, args, {
      cwd: root,
      env: { ...process.env, WRANGLER_SEND_METRICS: 'false', ...options.env },
      stdio: [options.input === undefined ? (capture ? 'ignore' : 'inherit') : 'pipe', capture ? 'pipe' : 'inherit', capture ? 'pipe' : 'inherit'],
      shell: false,
    });
    let stdout = '', stderr = '';
    if (capture) {
      child.stdout.on('data', value => { if (stdout.length < 2_000_000) stdout += value; });
      child.stderr.on('data', value => { if (stderr.length < 2_000_000) stderr += value; });
    }
    if (options.input !== undefined) {
      child.stdin.on('error', () => {});
      child.stdin.end(options.input);
    }
    child.on('error', reject);
    child.on('close', code => {
      if (code === 0 || options.allowFailure) resolvePromise({ code, stdout, stderr });
      else reject(new Error(options.sensitive
        ? `Uploading server secrets failed (exit ${code}). Check Cloudflare access, then run npm run launch again.`
        : `${options.label || 'Command'} failed (exit ${code}).${capture && (stderr || stdout) ? `\n${stderr || stdout}` : ''}`));
    });
  });
}

export async function wrangler(args, options = {}) {
  const cli = resolve(root, 'node_modules/wrangler/bin/wrangler.js');
  if (!await exists(cli)) throw new Error('Dependencies are missing. Run npm install first.');
  return command(process.execPath, [cli, ...args], options);
}

export async function npm(args, options = {}) {
  if (process.env.npm_execpath && await exists(process.env.npm_execpath)) {
    return command(process.execPath, [process.env.npm_execpath, ...args], options);
  }
  if (process.platform === 'win32') {
    // Arguments are fixed by these scripts, never supplied PINs or other secrets.
    return command(process.env.ComSpec || 'cmd.exe', ['/d', '/s', '/c', 'npm', ...args], options);
  }
  return command('npm', args, options);
}
